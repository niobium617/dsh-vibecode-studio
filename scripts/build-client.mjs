/**
 * Builds the client half to `lib/client.js` (plan D2).
 *
 * DSH loads client plugins as a plain script that registers a CommonJS factory:
 * `window.__ModuleLoader__.load({ id, factory })`. React stays external and is
 * provided through the factory's `require`.
 */
import { build } from 'esbuild'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const entry = join(root, 'src/client/index.ts')
const tmpDir = join(root, '.tmp/build')
const tmpFile = join(tmpDir, 'client.cjs')
const outfile = join(root, 'lib/client.js')

await mkdir(tmpDir, { recursive: true })
await mkdir(dirname(outfile), { recursive: true })

const result = await build({
  entryPoints: [entry],
  outfile: tmpFile,
  bundle: true,
  platform: 'browser',
  format: 'cjs',
  target: 'es2020',
  jsx: 'automatic',
  external: ['react', 'react/jsx-runtime'],
  logLevel: 'warning',
  legalComments: 'none',
  charset: 'utf8',
  metafile: true,
})

const code = await readFile(tmpFile, 'utf8')
const wrapped = `/* Generated by scripts/build-client.mjs — do not edit. */
window.__ModuleLoader__.load({
  id: 'dsh-vibecode-studio',
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${code}
    return module.exports;
  }
});
`
await writeFile(outfile, wrapped, 'utf8')

const bytes = Object.values(result.metafile.outputs).reduce((sum, output) => sum + output.bytes, 0)
console.log(`built ${relative(root, outfile)} (${(bytes / 1024).toFixed(1)} KiB)`)
