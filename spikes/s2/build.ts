/**
 * Build the T002 S2 spike package.
 *
 * Host: one no-op ESM module.
 * Client: a CommonJS bundle wrapped in the DSH loader envelope.
 */
import { build } from 'esbuild'
import { mkdir, readFile, stat, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const libDir = join(here, 'package', 'lib')
const buildDir = join(here, '.build')

async function fileSize(path: string): Promise<string> {
  return `${((await stat(path)).size / 1024).toFixed(1)} KiB`
}

async function buildHost(): Promise<void> {
  await mkdir(libDir, { recursive: true })
  await build({
    entryPoints: [join(here, 'host.ts')],
    outfile: join(libDir, 'index.js'),
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    logLevel: 'warning',
    legalComments: 'none',
  })
}

async function buildClient(): Promise<void> {
  await mkdir(buildDir, { recursive: true })
  const outfile = join(buildDir, 'client.cjs')
  await build({
    entryPoints: [join(here, 'client.tsx')],
    outfile,
    bundle: true,
    platform: 'browser',
    format: 'cjs',
    target: 'es2020',
    jsx: 'automatic',
    external: ['react', 'react/jsx-runtime'],
    logLevel: 'warning',
    legalComments: 'none',
    charset: 'utf8',
  })
  const code = await readFile(outfile, 'utf8')
  const wrapped = `/* Generated by spikes/s2/build.ts — do not edit. */
window.__ModuleLoader__.load({
  id: 'dsh-vibe-s2-spike',
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${code}
    return module.exports;
  }
});
`
  await writeFile(join(libDir, 'client.js'), wrapped, 'utf8')
}

await buildHost()
await buildClient()
console.log(`[vibe-s2] built host ${await fileSize(join(libDir, 'index.js'))} -> spikes/s2/package/lib/index.js`)
console.log(`[vibe-s2] built client ${await fileSize(join(libDir, 'client.js'))} -> spikes/s2/package/lib/client.js`)
console.log(`Next: dsh plugin --profile vibe-dev add link:${join(here, 'package').replaceAll('\\', '/')}`)
