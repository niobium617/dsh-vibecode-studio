/**
 * T001 S1 driver.
 *
 * 1. Bundles the host half into `package/lib/index.js` (jpeg-js inlined).
 * 2. Bundles the client half into `package/lib/client.js` wrapped in the
 *    `window.__ModuleLoader__.load({ id, factory })` envelope DSH expects.
 * 3. Runs the same frames/routes over loopback HTTP and prints a pull-vs-stream
 *    table. This is a transport smoke test, not a replacement for the 30 s
 *    Web/Desktop runs described in `REPORT.md`.
 *
 * Usage:
 *   pnpm tsx spikes/s1/run.ts [--build-only] [--seconds 10]
 */
import { build } from 'esbuild'
import { createServer, type Server } from 'node:http'
import { mkdir, readFile, stat, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { generateFrames, FRAME_COUNT, FRAME_HEIGHT, FRAME_QUALITY, FRAME_WIDTH } from './frames'
import { FrameSource } from './source'
import { createPullHandler, createStreamHandler, routeMeta } from './routes'
import {
  MultipartFrameParser,
  PULL_PATH,
  STREAM_PATH,
  type StreamFrame,
} from './protocol'

const here = dirname(fileURLToPath(import.meta.url))
const packageDir = join(here, 'package')
const libDir = join(packageDir, 'lib')
const buildDir = join(here, '.build')
const benchPath = join(here, 'bench.json')
const FPS = 30

type Mode = 'pull' | 'stream'

interface ModeStats {
  durationMs: number
  frames: number
  bytes: number
  firstFrameMs: number | null
  seqGaps: number
  duplicates: number
  droppedReported: number
  errors: number
  invalidFrames: number
  latencies: number[]
  fpsBySecond: number[]
  heapBefore: number
  heapAfter: number
  rssBefore: number
  rssAfter: number
}

interface BenchResult extends ModeStats {
  mode: Mode
  seconds: number
  fps: number
  kbps: number
  avgFrameBytes: number
  latency: { avg: number | null; p95: number | null; max: number | null }
}

function flag(name: string): string | undefined {
  const index = process.argv.indexOf(name)
  return index >= 0 ? process.argv[index + 1] : undefined
}

async function fileSize(path: string): Promise<string> {
  const info = await stat(path)
  return `${(info.size / 1024).toFixed(1)} KiB`
}

async function buildHost(): Promise<void> {
  await mkdir(libDir, { recursive: true })
  await build({
    entryPoints: [join(here, 'host.ts')],
    outfile: join(libDir, 'index.js'),
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    logLevel: 'warning',
    legalComments: 'none',
  })
}

async function buildClient(): Promise<void> {
  await mkdir(buildDir, { recursive: true })
  const outfile = join(buildDir, 'client.cjs')
  await build({
    entryPoints: [join(here, 'client.tsx')],
    outfile,
    bundle: true,
    platform: 'browser',
    format: 'cjs',
    target: 'es2020',
    jsx: 'automatic',
    external: ['react', 'react/jsx-runtime'],
    logLevel: 'warning',
    legalComments: 'none',
    charset: 'utf8',
  })
  const code = await readFile(outfile, 'utf8')
  const wrapped = `/* Generated by spikes/s1/run.ts — do not edit. */
window.__ModuleLoader__.load({
  id: 'dsh-vibe-s1-spike',
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${code}
    return module.exports;
  }
});
`
  await writeFile(join(libDir, 'client.js'), wrapped, 'utf8')
}

async function buildAll(): Promise<void> {
  await buildHost()
  await buildClient()
}

function num(value: string | null): number {
  const parsed = Number(value)
  return Number.isFinite(parsed) ? parsed : 0
}

function jpegLooksComplete(bytes: Uint8Array): boolean {
  return bytes.length > 4 &&
    bytes[0] === 0xff && bytes[1] === 0xd8 &&
    bytes[bytes.length - 2] === 0xff && bytes[bytes.length - 1] === 0xd9
}

function percentile(values: number[], p: number): number | null {
  if (values.length === 0) return null
  const sorted = [...values].sort((a, b) => a - b)
  return sorted[Math.min(sorted.length - 1, Math.floor(sorted.length * p))]
}

function average(values: number[]): number | null {
  if (values.length === 0) return null
  return values.reduce((sum, value) => sum + value, 0) / values.length
}

function round(value: number | null): number | null {
  return value === null ? null : Math.round(value * 10) / 10
}

function bucketise(times: number[], startedAt: number): number[] {
  const buckets: number[] = []
  for (const time of times) {
    const index = Math.floor((time - startedAt) / 1000)
    if (index < 0) continue
    while (buckets.length <= index) buckets.push(0)
    buckets[index] += 1
  }
  return buckets
}

async function createBenchServer(source: FrameSource): Promise<{ server: Server; base: string }> {
  const meta = routeMeta(source)
  const pull = createPullHandler(source, meta)
  const stream = createStreamHandler(source, meta)

  const server = createServer((request, response) => {
    void (async () => {
      const url = new URL(request.url ?? '/', 'http://127.0.0.1')
      const controller = new AbortController()
      response.on('close', () => controller.abort())
      let result: Response
      if (url.pathname === PULL_PATH) result = await pull(new Request(url, { signal: controller.signal }))
      else if (url.pathname === STREAM_PATH) result = await stream(new Request(url, { signal: controller.signal }))
      else {
        response.statusCode = 404
        response.end('not found')
        return
      }
      response.writeHead(result.status, Object.fromEntries(result.headers))
      if (result.body === null) {
        response.end()
        return
      }
      const reader = result.body.getReader()
      try {
        for (;;) {
          const { done, value } = await reader.read()
          if (done) break
          if (!response.write(Buffer.from(value))) {
            await new Promise<void>((resolve) => {
              const done = (): void => {
                response.off('drain', done)
                response.off('close', done)
                resolve()
              }
              response.once('drain', done)
              response.once('close', done)
            })
          }
        }
      } catch {
        // The benchmark aborts at its deadline; the server side just closes.
      }
      response.end()
    })().catch((error) => {
      if (!response.headersSent) response.statusCode = 500
      response.end(String(error))
    })
  })

  await new Promise<void>((resolve) => server.listen(0, '127.0.0.1', resolve))
  const address = server.address()
  if (address === null || typeof address === 'string') throw new Error('benchmark server did not bind')
  return { server, base: `http://127.0.0.1:${address.port}` }
}

function statsSkeleton(): ModeStats {
  const memory = process.memoryUsage()
  return {
    durationMs: 0,
    frames: 0,
    bytes: 0,
    firstFrameMs: null,
    seqGaps: 0,
    duplicates: 0,
    droppedReported: 0,
    errors: 0,
    invalidFrames: 0,
    latencies: [],
    fpsBySecond: [],
    heapBefore: memory.heapUsed,
    heapAfter: memory.heapUsed,
    rssBefore: memory.rss,
    rssAfter: memory.rss,
  }
}

function finishStats(stats: ModeStats, startedAt: number, endedAt: number, seconds: number): BenchResult {
  const memory = process.memoryUsage()
  stats.heapAfter = memory.heapUsed
  stats.rssAfter = memory.rss
  stats.durationMs = endedAt - startedAt
  return {
    ...stats,
    mode: 'pull',
    seconds,
    fps: Math.round((stats.frames / Math.max(0.001, (endedAt - startedAt) / 1000)) * 10) / 10,
    kbps: Math.round((stats.bytes / 1024 / Math.max(0.001, (endedAt - startedAt) / 1000)) * 10) / 10,
    avgFrameBytes: stats.frames === 0 ? 0 : Math.round(stats.bytes / stats.frames),
    latency: {
      avg: round(average(stats.latencies)),
      p95: round(percentile(stats.latencies, 0.95)),
      max: round(stats.latencies.length === 0 ? null : Math.max(...stats.latencies)),
    },
  }
}

async function benchPull(base: string, seconds: number): Promise<BenchResult> {
  const stats = statsSkeleton()
  const controller = new AbortController()
  const deadline = setTimeout(() => controller.abort(), seconds * 1000)
  const startedAt = Date.now()
  const arrivals: number[] = []
  let after = -1
  let lastSeq = -1

  try {
    while (!controller.signal.aborted) {
      const response = await fetch(`${base}${PULL_PATH}?wait=1&after=${after}`, {
        signal: controller.signal,
        cache: 'no-store',
      })
      if (!response.ok) {
        stats.errors += 1
        await new Promise((resolve) => setTimeout(resolve, 50))
        continue
      }
      const seq = num(response.headers.get('x-vibe-seq'))
      const ts = num(response.headers.get('x-vibe-ts'))
      const bytes = new Uint8Array(await response.arrayBuffer())
      const now = Date.now()
      stats.frames += 1
      stats.bytes += bytes.byteLength
      if (!jpegLooksComplete(bytes)) stats.invalidFrames += 1
      stats.latencies.push(Math.max(0, now - ts))
      if (stats.firstFrameMs === null) stats.firstFrameMs = now - startedAt
      if (lastSeq >= 0) {
        if (seq === lastSeq) stats.duplicates += 1
        else if (seq > lastSeq + 1) stats.seqGaps += seq - lastSeq - 1
      }
      lastSeq = Math.max(lastSeq, seq)
      arrivals.push(now)
      after = Math.max(after, seq)
    }
  } catch (error) {
    if (!controller.signal.aborted) stats.errors += 1
  } finally {
    clearTimeout(deadline)
  }

  const endedAt = Date.now()
  stats.fpsBySecond = bucketise(arrivals, startedAt)
  return { ...finishStats(stats, startedAt, endedAt, seconds), mode: 'pull' }
}

async function benchStream(base: string, seconds: number): Promise<BenchResult> {
  const stats = statsSkeleton()
  const controller = new AbortController()
  const deadline = setTimeout(() => controller.abort(), seconds * 1000)
  const startedAt = Date.now()
  const arrivals: number[] = []
  let lastSeq = -1

  try {
    const response = await fetch(`${base}${STREAM_PATH}`, {
      signal: controller.signal,
      cache: 'no-store',
    })
    if (!response.ok || response.body === null) throw new Error(`stream HTTP ${response.status}`)
    const reader = response.body.getReader()
    const parser = new MultipartFrameParser()
    while (!controller.signal.aborted) {
      const { done, value } = await reader.read()
      if (done) {
        if (!controller.signal.aborted) throw new Error('stream ended before the deadline')
        break
      }
      parser.push(value, (frame: StreamFrame) => {
        const now = Date.now()
        stats.frames += 1
        stats.bytes += frame.bytes.byteLength
        if (!jpegLooksComplete(frame.bytes)) stats.invalidFrames += 1
        stats.latencies.push(Math.max(0, now - frame.ts))
        if (stats.firstFrameMs === null) stats.firstFrameMs = now - startedAt
        if (frame.dropped > 0) stats.droppedReported += frame.dropped
        if (lastSeq >= 0) {
          if (frame.seq === lastSeq) stats.duplicates += 1
          else if (frame.seq > lastSeq + 1) stats.seqGaps += frame.seq - lastSeq - 1
        }
        lastSeq = Math.max(lastSeq, frame.seq)
        arrivals.push(now)
      })
    }
  } catch (error) {
    if (!controller.signal.aborted) stats.errors += 1
  } finally {
    clearTimeout(deadline)
  }

  const endedAt = Date.now()
  stats.fpsBySecond = bucketise(arrivals, startedAt)
  return { ...finishStats(stats, startedAt, endedAt, seconds), mode: 'stream' }
}

function pad(value: string | number, width: number): string {
  return String(value).padEnd(width)
}

function printTable(results: BenchResult[]): void {
  console.log('\nS1 local transport benchmark — same process, loopback HTTP')
  console.log(`${FRAME_WIDTH}x${FRAME_HEIGHT} JPEG q${FRAME_QUALITY} · ${FRAME_COUNT} synthetic frames · target ${FPS} fps`)
  console.log([
    pad('mode', 8), pad('sec', 5), pad('frames', 8), pad('fps', 7), pad('KB/s', 9),
    pad('frame', 8), pad('lat avg', 9), pad('lat p95', 9), pad('gaps', 6),
    pad('errors', 7), pad('invalid', 8), pad('rss +MB', 9),
  ].join(''))
  console.log('-'.repeat(100))
  for (const result of results) {
    console.log([
      pad(result.mode, 8), pad(result.seconds, 5), pad(result.frames, 8), pad(result.fps, 7),
      pad(result.kbps, 9), pad(result.avgFrameBytes, 8),
      pad(`${result.latency.avg ?? '—'}ms`, 9), pad(`${result.latency.p95 ?? '—'}ms`, 9),
      pad(result.seqGaps, 6), pad(result.errors, 7), pad(result.invalidFrames, 8),
      pad(((result.rssAfter - result.rssBefore) / 1024 / 1024).toFixed(1), 9),
    ].join(''))
  }
  console.log('-'.repeat(100))
  for (const result of results) {
    console.log(`${result.mode}: fpsBySecond = [${result.fpsBySecond.join(', ')}]`)
  }
}

async function runBenchmark(seconds: number): Promise<void> {
  console.log(`\n[vibe-s1] generating ${FRAME_COUNT} frames …`)
  const started = Date.now()
  const frames = generateFrames()
  const total = frames.reduce((sum, frame) => sum + frame.bytes.byteLength, 0)
  console.log(`[vibe-s1] frames ready in ${Date.now() - started} ms; ${(total / 1024).toFixed(1)} KiB (${(total / frames.length / 1024).toFixed(1)} KiB/frame)`)

  const source = new FrameSource(FPS)
  source.setFrames(frames)
  source.start()
  const { server, base } = await createBenchServer(source)
  try {
    const pull = await benchPull(base, seconds)
    const stream = await benchStream(base, seconds)
    printTable([pull, stream])
    await writeFile(benchPath, `${JSON.stringify({
      generatedAt: new Date().toISOString(),
      width: FRAME_WIDTH,
      height: FRAME_HEIGHT,
      quality: FRAME_QUALITY,
      frameCount: FRAME_COUNT,
      targetFps: FPS,
      seconds,
      results: [pull, stream],
    }, null, 2)}\n`, 'utf8')
    console.log('\nbenchmark JSON -> spikes/s1/bench.json')
    const failures = [pull, stream].filter((result) =>
      result.frames === 0 || result.fps < 10 || result.errors > 0 || result.invalidFrames > 0)
    if (failures.length > 0) {
      process.exitCode = 1
      console.log(`benchmark FAILED for: ${failures.map((result) => result.mode).join(', ')} (below 10 fps, no frames, errors, or invalid JPEGs)`)
    }
  } finally {
    source.stop()
    server.closeAllConnections?.()
    await new Promise<void>((resolve) => server.close(() => resolve()))
  }
}

async function main(): Promise<void> {
  const args = process.argv.slice(2)
  await buildAll()
  const hostSize = await fileSize(join(libDir, 'index.js'))
  const clientSize = await fileSize(join(libDir, 'client.js'))
  console.log(`[vibe-s1] built host ${hostSize} -> spikes/s1/package/lib/index.js`)
  console.log(`[vibe-s1] built client ${clientSize} -> spikes/s1/package/lib/client.js`)

  if (args.includes('--build-only')) return

  const seconds = Math.max(1, Number(flag('--seconds') ?? '10') || 10)
  await runBenchmark(seconds)
  console.log('\nNext: from the repo root, build before installing (package/lib is generated):')
  console.log('  pnpm spike:s1:build')
  console.log('  dsh plugin --profile vibe-dev add link:spikes/s1/package')
}

await main()
